"""Per-run folders: ``<artifact_dir>/runs/<run_id>/``.

- ``events.jsonl``: one ``HealEvent`` per line, appended.
- ``artifacts/<event_id>/<name>``: screenshots, patch files. Names are
  generated by HealWright (``HealEvent`` validates them), never page content.

Writes get one retry; failures are logged and never change a test outcome.
"""

from __future__ import annotations

import logging
from pathlib import Path

from ulid import ULID

from healwright.models import HealEvent

log = logging.getLogger("healwright.store")


def new_id() -> str:
    return str(ULID())


class RunStore:
    def __init__(self, root: Path, run_id: str | None = None) -> None:
        self.run_id = run_id or new_id()
        self.dir = root / "runs" / self.run_id
        self.events_path = self.dir / "events.jsonl"
        self.write_errors = 0

    def _try_twice(self, what: str, fn: object) -> bool:
        assert callable(fn)
        for attempt in (1, 2):
            try:
                fn()
                return True
            except OSError:
                if attempt == 2:
                    self.write_errors += 1
                    log.warning(
                        "healwright: could not write %s in %s", what, self.dir, exc_info=True
                    )
        return False

    def append_event(self, event: HealEvent) -> bool:
        line = event.model_dump_json() + "\n"

        def write() -> None:
            self.dir.mkdir(parents=True, exist_ok=True)
            with self.events_path.open("a", encoding="utf-8", newline="\n") as fh:
                fh.write(line)

        return self._try_twice("event", write)

    def save_artifact(self, event_id: str, name: str, data: bytes) -> str | None:
        """Save one artifact; returns its file name (for ``HealEvent.artifacts``) or None."""
        folder = self.dir / "artifacts" / event_id

        def write() -> None:
            folder.mkdir(parents=True, exist_ok=True)
            (folder / name).write_bytes(data)

        return name if self._try_twice(f"artifact {name}", write) else None

    def events(self) -> list[HealEvent]:
        if not self.events_path.is_file():
            return []
        return [
            HealEvent.model_validate_json(line)
            for line in self.events_path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]


__all__ = ["RunStore", "new_id"]
